export type IconName = keyof typeof P;

export function svg(name: IconName): string {
  return (
    '<svg viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" stroke-width="2" ' +
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' +
    P[name] +
    "</svg>"
  );
}

export function icon(name: IconName, cls = "ic"): HTMLSpanElement {
  return h("span", { class: cls, html: svg(name) });
}

/** WiFi signal bars for an RSSI in dBm. */
export function rssiLevel(rssi: number): number {
  return rssi >= -55 ? 4 : rssi >= -66 ? 3 : rssi >= -77 ? 2 : rssi > -127 && rssi < 0 ? 1 : 0;
}

export function bars(rssi: number): HTMLSpanElement {
  const lvl = rssiLevel(rssi);
  let r = "";
  for (let i = 0; i < 4; i++) {
    const ht = 5 + i * 5;
    r += `<rect x="${2 + i * 6}" y="${22 - ht}" width="4" height="${ht}" rx="1" opacity="${i < lvl ? 1 : 0.25}"/>`;
  }
  const words = ["no", "weak", "fair", "good", "excellent"];
  return h("span", {
    class: "ic bars",
    role: "img",
    "aria-label": words[lvl] + " signal",
    html: '<svg viewBox="0 0 24 24" width="24" height="24" fill="currentColor" aria-hidden="true">' + r + "</svg>",
  });
}
